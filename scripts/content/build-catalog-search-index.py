#!/usr/bin/env python3
"""Generate the compact, paged Dictionary search index migration.

The source catalog is validated by the content release pipeline. This generator emits
only public word fields plus normalized search columns, so Cloudflare request handlers
never import or validate the full catalog JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import unicodedata
from pathlib import Path


def normalize(value: object) -> str:
    text = unicodedata.normalize("NFD", str(value or "")).lower()
    text = "".join(char for char in text if unicodedata.category(char) != "Mn")
    return re.sub(r"[\s'’\-]+", "", text)


def sql(value: object) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def chunks(items: list[tuple[str, ...]], size: int = 100):
    for start in range(0, len(items), size):
        yield items[start : start + size]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", default="src/lib/content/catalog.json")
    parser.add_argument("--output", default="migrations/0013_catalog_search_index.sql")
    args = parser.parse_args()

    catalog_path = Path(args.catalog)
    output_path = Path(args.output)
    repository = json.loads(catalog_path.read_text(encoding="utf-8"))
    release_id = repository["activeReleaseByStandard"]["hsk3"]
    release = next(item for item in repository["releases"] if item["id"] == release_id)
    active_ids = set(release["contentAssetIds"])
    words = [
        asset
        for asset in repository["contentAssets"]
        if asset["id"] in active_ids
        and asset["kind"] == "word"
        and asset["standard"] == "hsk3"
        and asset["authorization"]["status"] == "authorized"
        and asset["qaStatus"] == "approved"
        and asset.get("publish_status") == "published"
    ]

    rows: list[tuple[str, ...]] = []
    for asset in words:
        payload = asset["payload"]
        hanzi = str(payload.get("hanzi", ""))
        traditional = str(payload.get("traditional", ""))
        pinyin = str(payload.get("pinyin", ""))
        meaning = str(payload.get("meaning", ""))
        part_of_speech = str(payload.get("partOfSpeech", "unspecified"))
        level_band = str(asset.get("level_band") or ("7-9" if int(asset["level"]) >= 7 else asset["level"]))
        sort_level = 7 if level_band == "7-9" else int(level_band)
        search_hanzi = normalize(hanzi + traditional)
        search_pinyin = normalize(pinyin)
        search_english = normalize(meaning)
        search_text = search_hanzi + " " + search_pinyin + " " + search_english
        rows.append(tuple(map(sql, (
            asset["id"], release_id, asset.get("standard_version", "GF0025-2021"),
            asset.get("content_version", ""), level_band, sort_level, hanzi, traditional,
            pinyin, meaning, part_of_speech, search_hanzi, search_pinyin,
            search_english, search_text,
        ))))

    columns = "(id,release_id,standard_version,content_version,level_band,sort_level,hanzi,traditional,pinyin,meaning,part_of_speech,search_hanzi,search_pinyin,search_english,search_text)"
    statements = [
        "-- Generated by scripts/content/build-catalog-search-index.py; do not edit.",
        "CREATE TABLE IF NOT EXISTS catalog_search_releases (id TEXT PRIMARY KEY, version INTEGER NOT NULL, published_at TEXT NOT NULL, word_count INTEGER NOT NULL, active INTEGER NOT NULL CHECK(active IN (0,1)));",
        "CREATE TABLE IF NOT EXISTS catalog_search_index (id TEXT NOT NULL, release_id TEXT NOT NULL, standard_version TEXT NOT NULL, content_version TEXT NOT NULL, level_band TEXT NOT NULL CHECK(level_band IN ('1','2','3','4','5','6','7-9')), sort_level INTEGER NOT NULL CHECK(sort_level BETWEEN 1 AND 7), hanzi TEXT NOT NULL, traditional TEXT NOT NULL, pinyin TEXT NOT NULL, meaning TEXT NOT NULL, part_of_speech TEXT NOT NULL, search_hanzi TEXT NOT NULL, search_pinyin TEXT NOT NULL, search_english TEXT NOT NULL, search_text TEXT NOT NULL, PRIMARY KEY(release_id,id));",
        "CREATE INDEX IF NOT EXISTS idx_catalog_search_release_level_pos ON catalog_search_index(release_id,level_band,part_of_speech,id);",
        "CREATE INDEX IF NOT EXISTS idx_catalog_search_release_sort ON catalog_search_index(release_id,sort_level,id);",
        "UPDATE catalog_search_releases SET active=0;",
        f"INSERT INTO catalog_search_releases(id,version,published_at,word_count,active) VALUES ({sql(release_id)},{int(release['version'])},{sql(release['publishedAt'])},{len(rows)},1) ON CONFLICT(id) DO UPDATE SET version=excluded.version,published_at=excluded.published_at,word_count=excluded.word_count,active=1;",
        f"DELETE FROM catalog_search_index WHERE release_id={sql(release_id)};",
    ]
    for group in chunks(rows):
        statements.append(f"INSERT INTO catalog_search_index {columns} VALUES\n" + ",\n".join("(" + ",".join(row) + ")" for row in group) + ";")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    generated = "\n".join(statements) + "\n"
    action = "generated"
    if output_path.exists():
        if output_path.read_text(encoding="utf-8") != generated:
            raise SystemExit(
                f"Refusing to rewrite immutable migration {output_path}. "
                "Use a new migration filename for a new or changed catalog release."
            )
        action = "verified"
    else:
        output_path.write_text(generated, encoding="utf-8")
    print(json.dumps({
        "action": action,
        "source": str(catalog_path),
        "output": str(output_path),
        "releaseId": release_id,
        "activeContentEntries": len(active_ids),
        "indexedWords": len(rows),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
