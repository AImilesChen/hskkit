const fs=require('node:fs'),assert=require('node:assert/strict');
const snapshot=require('../src/lib/content/hsk4-vocabulary-landing.json');
const html=fs.readFileSync('.next/server/app/vocabulary/4.html','utf8');
const rowLinks=[...html.matchAll(/<a\b[^>]*aria-label="View details for [^\"]+"[^>]*>/g)];
assert.equal(rowLinks.length,50,'HSK 4 first-page words must be present before JavaScript runs');
const anchors=[...html.matchAll(/<a\b[^>]*href="(\/word\/[^\"]+)"[^>]*>/g)].map(match=>match[1]);
for(const word of [...snapshot.firstPage,...snapshot.topics.flatMap(topic=>topic.words)])assert.ok(anchors.includes('/word/'+word.id),'Missing real HSK 4 entry');
assert.ok(html.includes('href="https://hskkit.com/vocabulary/4"'));
assert.ok(html.includes('HSK 4 Vocabulary List: 1,000 Words with Pinyin'));
assert.ok(html.includes('HSK 3.0')&&!html.includes('HSK 4.0'),'Syllabus version must remain HSK 3.0');
const schema=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'null');
const list=schema?.['@graph']?.find(item=>item['@type']==='ItemList');
assert.equal(list?.numberOfItems,50);
assert.deepEqual(list.itemListElement.map(item=>item.url),snapshot.firstPage.map(word=>'https://hskkit.com/word/'+word.id));
for(const id of ['hsk4-topics','hsk4-study-guide','hsk4-sources','hsk4-faq'])assert.ok(html.includes(`id="${id}"`)&&html.includes(`href="#${id}"`));
assert.ok(html.includes('我们正在讨论旅行的计划。')&&html.includes('2,000')&&html.includes('1,000'));
assert.ok((html.match(/<details\b/g)||[]).length>=6);
for(const level of [1,2,3,5,7])assert.ok(!fs.readFileSync(`.next/server/app/vocabulary/${level}.html`,'utf8').includes('data-hsk4-guide'));
assert.ok(fs.readFileSync('.next/server/app/vocabulary/1.html','utf8').includes('data-hsk1-guide'));
console.log('HSK 4 production HTML: 50 linked words, 18 topic entries, discussion example, count explanation, schemas and level isolation verified');
