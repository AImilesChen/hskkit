const fs=require('node:fs'),assert=require('node:assert/strict');
const snapshot=require('../src/lib/content/hsk6-vocabulary-landing.json');
const html=fs.readFileSync(process.argv[2] || '.next/server/app/vocabulary/6.html','utf8');
const rowLinks=[...html.matchAll(/<a\b[^>]*aria-label="View details for [^\"]+"[^>]*>/g)];
assert.equal(rowLinks.length,50,'HSK 6 first-page words must be present before JavaScript runs');
const anchors=[...html.matchAll(/<a\b[^>]*href="(\/word\/[^\"]+)"[^>]*>/g)].map(match=>match[1]);
for(const word of [...snapshot.firstPage,...snapshot.topics.flatMap(topic=>topic.words)])assert.ok(anchors.includes('/word/'+word.id),'Missing real HSK 6 entry');
assert.ok(html.includes('href="https://hskkit.com/vocabulary/6"'));
assert.ok(html.includes('HSK 6 Vocabulary List: 1,800 Words with Pinyin'));
assert.ok(html.includes('HSK 3.0')&&!html.includes('HSK 6.0'),'Syllabus version must remain HSK 3.0');
const schema=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'null');
const list=schema?.['@graph']?.find(item=>item['@type']==='ItemList');
assert.equal(list?.numberOfItems,50);
assert.deepEqual(list.itemListElement.map(item=>item.url),snapshot.firstPage.map(word=>'https://hskkit.com/word/'+word.id));
for(const id of ['hsk6-topics','hsk6-study-guide','hsk6-sources','hsk6-faq'])assert.ok(html.includes(`id="${id}"`)&&html.includes(`href="#${id}"`));
assert.ok(html.includes('这篇文章表达了作者的立场。')&&html.includes('5,400')&&html.includes('1,800'));
assert.ok((html.match(/<details\b/g)||[]).length>=6);
if (!process.argv[2]) for(const level of [1,2,3,4,5,7])assert.ok(!fs.readFileSync(`.next/server/app/vocabulary/${level}.html`,'utf8').includes('data-hsk6-guide'));
if (!process.argv[2]) assert.ok(fs.readFileSync('.next/server/app/vocabulary/1.html','utf8').includes('data-hsk1-guide'));
console.log('HSK 6 production HTML: 50 linked words, 18 topic entries, position example, count explanation, schemas and level isolation verified');
