const fs=require('node:fs'),assert=require('node:assert/strict');
const snapshot=require('../src/lib/content/hsk2-vocabulary-landing.json');
const html=fs.readFileSync('.next/server/app/vocabulary/2.html','utf8');
const rowLinks=[...html.matchAll(/<a\b[^>]*aria-label="View details for [^\"]+"[^>]*>/g)];
assert.equal(rowLinks.length,50,'HSK 2 first-page words must be present before JavaScript runs');
const anchors=[...html.matchAll(/<a\b[^>]*href="(\/word\/[^\"]+)"[^>]*>/g)].map(match=>match[1]);
for(const word of [...snapshot.firstPage,...snapshot.topics.flatMap(topic=>topic.words)])assert.ok(anchors.includes('/word/'+word.id),'Missing real HSK 2 entry');
assert.ok(html.includes('href="https://hskkit.com/vocabulary/2"'));
assert.ok(html.includes('HSK 2 Vocabulary List: 200 Words with Pinyin'));
const schema=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'null');
const list=schema?.['@graph']?.find(item=>item['@type']==='ItemList');
assert.equal(list?.numberOfItems,50);
assert.deepEqual(list.itemListElement.map(item=>item.url),snapshot.firstPage.map(word=>'https://hskkit.com/word/'+word.id));
for(const id of ['hsk2-topics','hsk2-study-guide','hsk2-sources','hsk2-faq'])assert.ok(html.includes(`id="${id}"`)&&html.includes(`href="#${id}"`));
assert.ok(html.includes('地铁比公交车快。')&&html.includes('500')&&html.includes('200'));
assert.ok((html.match(/<details\b/g)||[]).length>=6);
for(const level of [1,3,7])assert.ok(!fs.readFileSync(`.next/server/app/vocabulary/${level}.html`,'utf8').includes('data-hsk2-guide'));
assert.ok(fs.readFileSync('.next/server/app/vocabulary/1.html','utf8').includes('data-hsk1-guide'));
console.log('HSK 2 production HTML: 50 linked words, 18 topic entries, comparison example, count explanation, schemas and level isolation verified');
